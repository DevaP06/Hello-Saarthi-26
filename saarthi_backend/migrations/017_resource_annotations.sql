CREATE TABLE IF NOT EXISTS saarthi_material_annotations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES saarthi_users(id) ON DELETE CASCADE,
    material_id INTEGER NOT NULL REFERENCES saarthi_materials(id) ON DELETE CASCADE,
    document_version VARCHAR(64) NOT NULL,
    page INTEGER NOT NULL,
    quote TEXT NOT NULL,
    note TEXT NOT NULL,
    rectangles JSON NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_material_annotations_document ON saarthi_material_annotations (user_id, material_id, document_version);
